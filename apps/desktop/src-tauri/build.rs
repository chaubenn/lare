use std::path::{Path, PathBuf};

fn main() {
    stage_zvec();
    let commands = registered_commands();
    write_main_window_set(commands);
    check_overlay_set(commands);
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("tauri-build failed");
}

/// Every command in `lib.rs`'s `generate_handler!`, which is the only hand-written list of them.
/// With an app manifest Tauri checks app commands against the capabilities as it does plugin
/// commands; without one any window could call any of them. Each gets an `allow-<name>`
/// permission, granted per window through the sets in `permissions/`.
fn registered_commands() -> &'static [&'static str] {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let lib: &'static str = Box::leak(
        std::fs::read_to_string("src/lib.rs")
            .expect("read src/lib.rs")
            .into_boxed_str(),
    );
    let start = lib
        .find("generate_handler![")
        .expect("generate_handler! in src/lib.rs")
        + "generate_handler![".len();
    let end = start + lib[start..].find(']').expect("end of generate_handler!");
    let commands: Vec<&'static str> = lib[start..end]
        .lines()
        .map(|line| line.split("//").next().unwrap_or_default())
        .flat_map(|line| line.split(','))
        .map(|item| item.trim().rsplit("::").next().unwrap_or_default())
        .filter(|name| !name.is_empty())
        .collect();
    assert!(
        !commands.is_empty(),
        "generate_handler! in src/lib.rs lists no commands"
    );
    Box::leak(commands.into_boxed_slice())
}

fn permission_for(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

/// The main window may call every command, so its permission set is generated rather than kept in
/// step by hand. Only rewritten when it changes: tauri-build watches `permissions/`, and a fresh
/// mtime on every run would rebuild the crate forever.
fn write_main_window_set(commands: &[&str]) {
    let path = Path::new("permissions/main-window.toml");
    let mut set = String::from(
        "# Generated by build.rs from `generate_handler!` in src/lib.rs. Do not edit.\n\n\
         [[set]]\n\
         identifier = \"main-window\"\n\
         description = \"Every app command: the main window is the app.\"\n\
         permissions = [\n",
    );
    for command in commands {
        set.push_str(&format!("  \"{}\",\n", permission_for(command)));
    }
    set.push_str("]\n");
    let current = std::fs::read_to_string(path).unwrap_or_default();
    if current.replace("\r\n", "\n") != set {
        std::fs::write(path, set).expect("write permissions/main-window.toml");
    }
}

/// The overlay windows get a hand-picked subset (`permissions/app.toml`). A permission there that
/// names no registered command would only fail once tauri-build resolves the capabilities, with a
/// message that does not say where the name came from.
fn check_overlay_set(commands: &[&str]) {
    println!("cargo:rerun-if-changed=permissions/app.toml");
    let sets = std::fs::read_to_string("permissions/app.toml").expect("read permissions/app.toml");
    let granted: Vec<&str> = sets
        .lines()
        .map(|line| line.split('#').next().unwrap_or_default())
        .flat_map(|line| line.split('"'))
        .filter(|item| item.starts_with("allow-"))
        .collect();
    assert!(
        !granted.is_empty(),
        "permissions/app.toml grants the overlay windows nothing"
    );
    for permission in granted {
        assert!(
            commands
                .iter()
                .any(|command| permission_for(command) == permission),
            "permissions/app.toml grants `{permission}`, which is not a command registered in src/lib.rs"
        );
    }
}

/// Zvec (the palette's search index) is a shared library the app has to ship beside itself.
/// Copy it to `target/zvec/`, where `tauri.windows.conf.json` (next to the exe) and the macOS
/// `frameworks` list (into `Contents/Frameworks`, which tauri-build puts on the rpath) pick it
/// up. This runs before tauri-build because that checks the bundled files exist.
///
/// On Windows the DLL is also delay-loaded: its initialisers use AVX, so loading it with the exe
/// would kill the app on a CPU without AVX before `search::engine` could check for it.
fn stage_zvec() {
    zvec_rust_build::configure();
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dest = manifest.join("../../../target/zvec");
    match zvec_rust_build::copy_runtime_libs_to(&dest) {
        Ok(copied) if copied.is_empty() => {
            println!("cargo:warning=Zvec's shared library was not found; the bundle will lack it");
        }
        Ok(_) => {}
        Err(e) => println!("cargo:warning=could not stage Zvec's shared library: {e}"),
    }
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        println!("cargo:rustc-link-arg=/DELAYLOAD:zvec_c_api.dll");
        println!("cargo:rustc-link-lib=delayimp");
    }
}
